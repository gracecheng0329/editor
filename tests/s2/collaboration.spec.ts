import { test, expect } from '@playwright/test';
import { registeredUser } from '../s1/sharing-fixtures';

const origin = 'http://127.0.0.1:3102';
test('two authorized identities see each other and collaborate on nodes', async ({ browser }) => {
  const owner = await registeredUser();
  const editor = await registeredUser();
  const a = await browser.newContext();
  const b = await browser.newContext();
  try {
    await owner.client.auth.updateUser({ data: { name: 'Alice' } });
    await editor.client.auth.updateUser({ data: { name: 'Bob' } });
    await a.addCookies(owner.browserCookies().map(cookie => ({ ...cookie, url: origin })));
    await b.addCookies(editor.browserCookies().map(cookie => ({ ...cookie, url: origin })));
    const created = await a.request.post('/api/documents', { headers: { Origin: origin }, data: { title: 'Collaboration' } });
    expect(created.status()).toBe(201);
    const doc = await created.json();
    expect((await a.request.post(`/api/documents/${doc.id}/editors`, { headers: { Origin: origin }, data: { userId: editor.id } })).status()).toBe(200);
    const alice = await a.newPage();
    const bob = await b.newPage();
    await Promise.all([alice.goto(`/documents/${doc.id}`), bob.goto(`/documents/${doc.id}`)]);
    await expect(alice.getByLabel('協作者')).toContainText('Bob');
    await expect(bob.getByLabel('協作者')).toContainText('Alice');
    await alice.getByLabel('新增節點名稱').fill('Shared service');
    await alice.getByRole('button', { name: '新增節點', exact: true }).click();
    await expect(bob.getByLabel('畫布節點')).toContainText('Shared service', { timeout: 2000 });
    const canvas = alice.getByLabel('文件畫布', { exact: true });
    await Promise.all([canvas.scrollIntoViewIfNeeded(), bob.getByLabel('文件畫布', { exact: true }).scrollIntoViewIfNeeded()]);
    const box = (await canvas.boundingBox())!;
    await alice.mouse.move(box.x + 280, box.y + 230);
    await alice.mouse.move(box.x + 300, box.y + 250, { steps: 5 });
    await expect(bob.locator('.tl-collaborator__cursor')).toBeVisible();
    await bob.getByLabel('文件畫布', { exact: true }).screenshot({ path: '/private/tmp/editor-s2-collaboration.png' });
    await bob.getByRole('button', { name: '選取 Shared service', exact: true }).click();
    await expect(alice.getByLabel('選取節點名稱')).toHaveCount(0);
    await bob.getByLabel('選取節點名稱').fill('Edited by Bob');
    await expect(alice.getByLabel('畫布節點')).toContainText('Edited by Bob', { timeout: 2000 });
    await bob.getByRole('button', { name: '向右移動節點' }).click();
    await expect(alice.getByLabel('畫布節點')).toContainText('x:140', { timeout: 2000 });
    await alice.getByRole('button', { name: '選取 Edited by Bob', exact: true }).click();
    const bobShape = bob.locator('.tl-shape').filter({ hasText: 'Edited by Bob' }).first();
    const beforeView = await bobShape.boundingBox();
    const aliceShape = alice.locator('.tl-shape').filter({ hasText: 'Edited by Bob' }).first();
    const beforeAliceView = await aliceShape.boundingBox();
    await alice.mouse.move(box.x + 350, box.y + 300);
    await alice.mouse.wheel(0, -400);
    await expect.poll(async () => aliceShape.boundingBox()).not.toEqual(beforeAliceView);
    await expect.poll(async () => bobShape.boundingBox()).toEqual(beforeView);
    await alice.mouse.click(box.x + 40, box.y + 40);
    await expect(bob.getByLabel('選取節點名稱')).toHaveValue('Edited by Bob');
    await alice.getByRole('button', { name: '選取 Edited by Bob', exact: true }).click();
    await Promise.all([alice.getByRole('button', { name: '向右移動節點' }).click(), bob.getByRole('button', { name: '向右移動節點' }).click()]);
    await expect.poll(async () => (await alice.getByLabel('畫布節點').innerText()) === (await bob.getByLabel('畫布節點').innerText()), { timeout: 5000 }).toBe(true);
    await expect(alice.getByLabel('畫布節點').getByRole('listitem')).toHaveCount(1);
    await expect(bob.getByLabel('畫布節點').getByRole('listitem')).toHaveCount(1);
    await expect(bob.getByLabel('保存狀態')).toHaveText('已確認持久化');
    await expect(alice.getByLabel('保存狀態')).toHaveText('已確認持久化');
    await bob.getByLabel('新增節點名稱').fill('Temporary node');
    await bob.getByRole('button', { name: '新增節點', exact: true }).click();
    await expect(alice.getByLabel('畫布節點')).toContainText('Temporary node', { timeout: 2000 });
    await alice.getByRole('button', { name: '選取 Temporary node', exact: true }).click();
    await alice.getByRole('button', { name: '刪除選取節點' }).click();
    await expect(bob.getByLabel('畫布節點')).not.toContainText('Temporary node', { timeout: 2000 });
    await expect(alice.getByLabel('保存狀態')).toHaveText('已確認持久化');
    await b.close();
    await expect(alice.getByLabel('協作者')).not.toContainText('Bob');
    const restart = await fetch('http://127.0.0.1:8790/restart', { method: 'POST', headers: { Authorization: `Bearer ${process.env.SYNC_TEST_SECRET}` } });
    expect(restart.status).toBe(200);
    const runtimes = await restart.json();
    expect(runtimes.runtimeId).not.toBe(runtimes.previousRuntimeId);
    await alice.reload();
    await expect(alice.getByLabel('畫布節點')).toContainText('Edited by Bob');
    await expect(alice.getByLabel('協作者')).not.toContainText('Bob');
    await alice.getByRole('button', { name: '選取 Edited by Bob', exact: true }).click();
    await alice.getByRole('button', { name: '刪除選取節點' }).click();
    await expect(alice.getByLabel('保存狀態')).toHaveText('已確認持久化');
    await alice.reload();
    await expect(alice.getByLabel('畫布節點')).not.toContainText('Edited by Bob');
  } finally { await a.close(); await b.close(); await editor.cleanup(); await owner.cleanup(); }
});
